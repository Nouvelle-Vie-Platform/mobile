/// La référence de repli du jour [day].
BibleLink fallbackVerseFor(DateTime day) {
  // En UTC : un changement d'heure ne décale pas le compte.
  final dayOfYear = DateTime.utc(
    day.year,
    day.month,
    day.day,
  ).difference(DateTime.utc(day.year)).inDays;
  return parseFallbackVerse(fallbackVerses[dayOfYear.clamp(0, 364)]);
}

/// `'1John 4:7-8'` → `BibleLink('1John', 4, from: 7, to: 8)`.
BibleLink parseFallbackVerse(String ref) {
  final [book, place] = ref.split(' ');
  final [chapter, verses] = place.split(':');
  final range = verses.split('-').map(int.parse).toList();
  return BibleLink(
    book,
    int.parse(chapter),
    from: range.first,
    to: range.length > 1 ? range.last : null,
  );
}
